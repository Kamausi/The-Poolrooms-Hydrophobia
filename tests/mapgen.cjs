// Endless mode: each depth's dock is a WFC variation of its attraction's map, built in a worker while you ride.
const { open, check, finish } = require('./lib.cjs');
(async () => {
  const { browser, page, errors } = await open({ width: 800, height: 450 });
  const out = [];
  for (let i = 0; i < 4; i++) {
    await page.evaluate((i) => { const u = window.__underflow; if (i === 0) u.startEndless(4242); u.beginSector(i); u.startRide(); u.setState({ health: 1e6 }); u.step(2); }, i);
    await page.waitForTimeout(600);
    out.push(await page.evaluate((i) => { const u = window.__underflow; u.startExplore(); u.setState({ health: 1e6 }); u.step(20); const E = window.__explore, g = u.state.genMaps?.[i];
      return { i, endless: u.state.endless, ready: !!g, worker: g?.worker, fallback: g?.fallback, same: !!g && E.rows.join() === g.map.join(), docks: E.find('D').length }; }, i));
  }
  check('endless docks are generated by WFC in a worker, solvable, and the dock you walk is the generated one', out.every((o) => o.endless && o.ready && o.worker && !o.fallback && o.same && o.docks === 1), JSON.stringify(out));
  await finish(browser, errors);
})();
